#!/usr/bin/env python3
"""X11 misc-fixed bitmap font (PCF, public domain) -> C header for port3ds/deck.c.
Usage: gen_font.py <font.pcf[.gz]> <out.h> <cellW> <cellH> <NAME>
Crisp 1-bit glyphs: the Micropolis port showed scaled/anti-aliased text reads badly on the 3DS LCD."""
import sys, os, gzip, tempfile, io
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
src, out, W, H, NAME = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), sys.argv[5]
data = open(src, "rb").read()
if src.endswith(".gz"): data = gzip.decompress(data)
tmp = tempfile.mkdtemp()
PcfFontFile.PcfFontFile(io.BytesIO(data)).save(os.path.join(tmp, "f"))
font = ImageFont.load(os.path.join(tmp, "f.pil"))
N = NAME.upper()
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_font.py from X11 misc-fixed (public domain). Do not edit. */\n#pragma once\n#include <stdint.h>\n")
    f.write("#define %s_W %d\n#define %s_H %d\n" % (N, W, N, H))
    f.write("/* glyphs 0x20..0x7E, one uint16 row bitmap per line, MSB = leftmost pixel of a %d-wide cell */\n" % W)
    f.write("static const uint16_t %s_bits[95][%d] = {\n" % (NAME, H))
    for cp in range(0x20, 0x7F):
        im = Image.new("1", (W, H), 0)
        ImageDraw.Draw(im).text((0, 0), chr(cp), font=font, fill=1)
        px = im.load()
        rows = [sum((1 << (15 - x)) for x in range(W) if px[x, y]) for y in range(H)]
        f.write("{" + ",".join("0x%04X" % r for r in rows) + "}, /* %r */\n" % chr(cp))
    f.write("};\n")
print("wrote", out)
