#!/usr/bin/env python3
"""Build port3ds/manual_text.h from port3ds/manual.txt (the in-game manual).

Usage: embed_manual.py [port3ds dir]. Run by build-uqm.sh before every build,
so editing manual.txt is all it takes to change the built-in manual."""
import os, sys

d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "port3ds")
src = open(os.path.join(d, "manual.txt"), encoding="utf-8").read()
src = src.encode("ascii", "replace").decode("ascii")   # the deck fonts are ASCII
out = ["/* Generated by tools/embed_manual.py from manual.txt. Edit manual.txt. */",
       "static const char manual_builtin[] ="]
for line in src.split("\n"):
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    out.append('\t"%s\\n"' % esc)
out[-1] += ";"
new = "\n".join(out) + "\n"
path = os.path.join(d, "manual_text.h")
old = open(path).read() if os.path.exists(path) else ""
if old != new:          # keep the timestamp when nothing changed: no needless rebuild
    open(path, "w").write(new)
print("embed_manual: %d bytes of manual" % len(src))
